drop table if exists user_profiles cascade;
drop table if exists users cascade;
create table user_profiles
(
    id           integer generated by default as identity,
    created_date timestamp(6) with time zone default NOW() not null,
    full_name    varchar(255)                              not null,
    primary key (id)
);
create table users
(
    id              integer generated by default as identity,
    user_profile_id integer unique,
    created_date    timestamp(6) with time zone default NOW() not null,
    username        varchar(255)                              not null unique,
    primary key (id)
);
alter table if exists users add constraint fk_user_profile_id foreign key (user_profile_id) references user_profiles;

alter table if exists accounts drop constraint if exists fk_customer_id;
alter table if exists notifications drop constraint if exists fk_customer_id;
drop table if exists accounts cascade;
drop table if exists customers cascade;
drop table if exists fund_transfer_audits cascade;
drop table if exists notifications cascade;
create table accounts
(
    account_balance numeric(19, 4) not null,
    customer_id     bigint         not null,
    id              bigint generated by default as identity,
    account_number  varchar(255)   not null unique,
    account_type    varchar(255)   not null check ((account_type in ('CHECKING', 'SAVINGS'))),
    primary key (id)
);
create table customers
(
    id        bigint generated by default as identity,
    full_name varchar(255) not null,
    primary key (id)
);
create table fund_transfer_audits
(
    amount                     numeric(19, 4)                            not null,
    created_date               timestamp(6) with time zone default NOW() not null,
    id                         bigint generated by default as identity,
    audit_status               varchar(255)                              not null check ((audit_status in ('FAILED', 'SUCCESS', 'INSUFFICIENT_FUNDS', 'ORIGIN_ACCOUNT_NUMBER_NOT_FOUND', 'DESTINATION_ACCOUNT_NUMBER_NOT_FOUND'))),
    audit_type                 varchar(255)                              not null check ((audit_type in ('DEBIT', 'CREDIT', 'REFUND'))),
    destination_account_number varchar(255),
    origin_account_number      varchar(255),
    reference_id               varchar(255)                              not null,
    primary key (id)
);
create table notifications
(
    created_date timestamp(6) with time zone not null,
    customer_id  bigint                      not null,
    id           bigint generated by default as identity,
    message      TEXT                        not null,
    primary key (id)
);
create index idx_fund_transfer_audit_reference_id on fund_transfer_audits (reference_id);
create index idx_fund_transfer_audit_reference_id_audit_type on fund_transfer_audits (reference_id, audit_type);
create index idx_fund_transfer_audit_origin_acccount_number on fund_transfer_audits (origin_account_number);
create index idx_fund_transfer_audit_destination_acccount_number on fund_transfer_audits (destination_account_number);
create index idx_fund_transfer_created_date on fund_transfer_audits (created_date desc);
alter table if exists accounts add constraint fk_customer_id foreign key (customer_id) references customers;
alter table if exists notifications add constraint fk_customer_id foreign key (customer_id) references customers;